from fastapi import FastAPI, HTTPException, Request
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field, ValidationError

from .evidence import AnalysisResponse, EvidenceBundle
from .correlation import RULE_SET_VERSION, correlate, validate_references
from .legal_rag import LegalSearchRequest, current_corpus_version, search_legal_sources, list_legal_sources
from .policy_fetch import PolicyFetchError, fetch_policy
from .risk import assign_review_priorities

app = FastAPI(
    title="TRUSTTRACE AI API",
    description="Local API for policy extraction, source-grounded DPDP retrieval, and deterministic evidence review.",
    version="0.4.0",
)

# The unpacked extension ID is generated by Chrome. Permit only extension origins;
# the API itself is intended to bind to loopback during local development.
app.add_middleware(
    CORSMiddleware,
    allow_origin_regex=r"^chrome-extension://[a-p]{32}$",
    allow_methods=["GET", "POST"],
    allow_headers=["content-type"],
    allow_credentials=False,
)


class PolicyExtractRequest(BaseModel):
    url: str = Field(min_length=1, max_length=2048)


class PolicyExcerpt(BaseModel):
    source_url: str
    start: int = Field(description="Zero-based Unicode code-point offset into the returned text.")
    end: int = Field(description="Exclusive zero-based Unicode code-point offset into the returned text.")
    text: str = Field(description="Exactly equal to text[start:end] in the response using Python Unicode code-point indexing.")


class PolicyExtractResponse(BaseModel):
    source_url: str
    text: str = Field(description="Whitespace-normalized extracted text; excerpt offsets index this exact string.")
    excerpts: list[PolicyExcerpt]
    truncated: bool
    redirect_count: int


MAX_ANALYSIS_REQUEST_BYTES = 512 * 1024


def analyze_evidence_bundle(bundle: EvidenceBundle, *, index_path=None) -> dict[str, object]:
    """Analyze a bounded, already-collected bundle; this function does no I/O."""
    legal: list[dict[str, object]] = []
    legal_evidence_status = "not_supplied"
    limitations = [
        "Browser observations are client-provided request metadata and do not reveal payloads, request purpose, or personal-data transfer.",
        "Policy statements are recorded as claims only; this analysis does not determine truth, adequacy, legal applicability, or violations.",
        "Legal passages are lexical category candidates only and do not establish applicability or a legal conclusion.",
        "No current Phase 4 rule produces a high priority; the available inputs cannot substantiate one defensibly.",
    ]
    corpus_status = "available"
    try:
        corpus_version = current_corpus_version(index_path) if index_path else current_corpus_version()
        legal, legal_evidence_status = validate_references(bundle, index_path=index_path)
    except FileNotFoundError:
        corpus_status = "unavailable"
        corpus_version = None
        legal_evidence_status = "unavailable"
        limitations.append("The local legal corpus is unavailable; no client-supplied legal reference was accepted or treated as negative evidence.")
        if bundle.legal_references:
            limitations.append("Supplied legal references could not be verified because the corpus is unavailable.")
    findings = assign_review_priorities(correlate(bundle, legal))
    return AnalysisResponse(
        rule_set_version=RULE_SET_VERSION,
        corpus_status=corpus_status,
        corpus_version=corpus_version,
        legal_evidence_status=legal_evidence_status,
        verified_legal_references=legal,
        findings=findings,
        limitations=limitations,
    ).model_dump(mode="json")


@app.get("/health", tags=["health"])
def health_check() -> dict[str, str]:
    """Simple readiness endpoint for local development."""
    return {"status": "ok", "service": "trusttrace-api", "phase": "0"}


@app.post("/policy/extract", tags=["policy"], response_model=PolicyExtractResponse)
async def extract_policy(request: PolicyExtractRequest) -> dict[str, object]:
    """Fetch a user-selected policy URL and return literal extracted text."""
    try:
        return await fetch_policy(request.url)
    except PolicyFetchError as error:
        raise HTTPException(status_code=error.status_code, detail=str(error)) from error


@app.get("/legal/sources", tags=["legal"])
def legal_sources() -> dict[str, object]:
    """List the fixed, official-source registry used by Phase 3."""
    return {"sources": list_legal_sources()}


@app.post("/legal/search", tags=["legal"])
def legal_search(request: LegalSearchRequest) -> dict[str, object]:
    """Retrieve exact provision passages; this endpoint makes no legal finding."""
    try:
        return search_legal_sources(request.query, limit=request.limit)
    except FileNotFoundError as error:
        raise HTTPException(status_code=503, detail="Legal corpus is not initialized. Run the documented source-ingestion command.") from error


@app.post("/analysis/evidence", tags=["analysis"], response_model=AnalysisResponse)
async def analyze_evidence(request: Request) -> dict[str, object]:
    """Validate and correlate supplied evidence without fetching URLs or calling an LLM."""
    if request.headers.get("content-type", "").split(";", 1)[0].strip().lower() != "application/json":
        raise HTTPException(status_code=415, detail="Evidence bundles must use application/json.")
    body = bytearray()
    async for chunk in request.stream():
        body.extend(chunk)
        if len(body) > MAX_ANALYSIS_REQUEST_BYTES:
            raise HTTPException(status_code=413, detail="Evidence bundle exceeds the 512 KB request limit.")
    try:
        bundle = EvidenceBundle.model_validate_json(bytes(body))
        return analyze_evidence_bundle(bundle)
    except ValidationError as error:
        raise HTTPException(status_code=422, detail=error.errors(include_input=False)) from error
    except ValueError as error:
        raise HTTPException(status_code=422, detail=str(error)) from error
